/**
 * Extracts the brand glyph paths we use into `lib/data/tech-icons.ts`.
 *
 * Why generate instead of importing at runtime: `simple-icons` carries ~3000
 * icons and we need thirteen. Baking the paths in keeps it a devDependency and
 * ships nothing extra, while still guaranteeing the path data is real rather
 * than hand-copied.
 *
 * Run with `npm run gen:icons` after changing the list below.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import * as si from "simple-icons";

// `simple-icons` doesn't export ./package.json, so resolve the entry point and
// walk up to the package root for the version stamp.
const require = createRequire(import.meta.url);
const { version } = JSON.parse(
  readFileSync(
    new URL("package.json", pathToFileURL(require.resolve("simple-icons")).href.replace(/[^/]+$/, "")),
    "utf8",
  ),
);

// key -> simple-icons slug. Keys are what `lib/data/stack.ts` refers to.
const WANTED = {
  java: "openjdk", // Simple Icons dropped the Java mark; OpenJDK is the stand-in
  go: "go",
  python: "python",
  springboot: "springboot",
  kubernetes: "kubernetes",
  terraform: "terraform",
  docker: "docker",
  openshift: "redhatopenshift",
  prometheus: "prometheus",
  grafana: "grafana",
  helm: "helm",
  jenkins: "jenkins",
  githubactions: "githubactions",
  linux: "linux",
};

const entries = Object.entries(WANTED).map(([key, slug]) => {
  const icon = si["si" + slug[0].toUpperCase() + slug.slice(1)];
  if (!icon) throw new Error(`simple-icons has no "${slug}" (for key "${key}")`);
  return [key, icon];
});

const body = entries
  .map(([key, icon]) => `  ${key}: {\n    title: ${JSON.stringify(icon.title)},\n    path: ${JSON.stringify(icon.path)},\n  },`)
  .join("\n");

writeFileSync(
  new URL("../lib/data/tech-icons.ts", import.meta.url),
  `// GENERATED by scripts/gen-tech-icons.mjs — do not edit by hand.
// Paths from simple-icons v${version}, licensed CC0-1.0.
export type TechIcon = { title: string; path: string };

export const techIcons: Record<string, TechIcon> = {
${body}
};
`,
);

console.log(`wrote ${entries.length} icons`);
