/**
 * Extracts the brand glyph paths we use into `lib/data/tech-icons.ts`.
 *
 * Why generate instead of importing at runtime: the icon sets carry thousands of
 * icons and we need a handful. Baking the paths in keeps them devDependencies
 * and ships nothing extra, while still guaranteeing the path data is real
 * rather than hand-copied.
 *
 * Two sources, because neither covers the stack alone:
 * - `simple-icons` (CC0) is the default.
 * - `@iconify-json/fa6-brands` (Font Awesome Free, CC BY 4.0) fills the gaps
 *   Simple Icons dropped over trademark policy — AWS most notably.
 *
 * Run with `npm run gen:icons` after changing the list below.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import * as si from "simple-icons";

const require = createRequire(import.meta.url);

// `simple-icons` doesn't export ./package.json, so resolve the entry point and
// walk up to the package root for the version stamp.
const { version: siVersion } = JSON.parse(
  readFileSync(
    new URL(
      "package.json",
      pathToFileURL(require.resolve("simple-icons")).href.replace(/[^/]+$/, ""),
    ),
    "utf8",
  ),
);

const fa = require("@iconify-json/fa6-brands/icons.json");

/**
 * key -> source + slug. Keys are what `lib/data/stack.ts` refers to.
 * `fa:` entries are Font Awesome; everything else is Simple Icons.
 */
const WANTED = {
  java: "fa:java",
  go: "go",
  python: "python",
  springboot: "springboot",
  kubernetes: "kubernetes",
  aws: "fa:aws", // Simple Icons has no Amazon/AWS mark
  terraform: "terraform",
  docker: "docker",
  openshift: "redhatopenshift",
  prometheus: "prometheus",
  grafana: "grafana",
  helm: "helm",
  jenkins: "jenkins",
  githubactions: "githubactions",
  linux: "linux",
};

function fromSimpleIcons(slug, key) {
  const icon = si["si" + slug[0].toUpperCase() + slug.slice(1)];
  if (!icon) throw new Error(`simple-icons has no "${slug}" (for key "${key}")`);
  return { title: icon.title, path: icon.path, viewBox: "0 0 24 24" };
}

function fromFontAwesome(slug, key) {
  const icon = fa.icons[slug];
  if (!icon) throw new Error(`fa6-brands has no "${slug}" (for key "${key}")`);

  const paths = icon.body.match(/<path\b[^>]*>/g) ?? [];
  if (paths.length !== 1) {
    throw new Error(`"${slug}" is not a single path — needs manual handling`);
  }
  const d = paths[0].match(/\sd="([^"]+)"/)?.[1];
  if (!d) throw new Error(`could not read path data for "${slug}"`);

  const width = icon.width ?? fa.width ?? 512;
  const height = icon.height ?? fa.height ?? 512;
  return { title: slug, path: d, viewBox: `0 0 ${width} ${height}` };
}

const entries = Object.entries(WANTED).map(([key, spec]) => {
  const icon = spec.startsWith("fa:")
    ? fromFontAwesome(spec.slice(3), key)
    : fromSimpleIcons(spec, key);
  return [key, icon];
});

const body = entries
  .map(
    ([key, icon]) =>
      `  ${key}: {\n    title: ${JSON.stringify(icon.title)},\n    viewBox: ${JSON.stringify(icon.viewBox)},\n    path: ${JSON.stringify(icon.path)},\n  },`,
  )
  .join("\n");

writeFileSync(
  new URL("../lib/data/tech-icons.ts", import.meta.url),
  `// GENERATED by scripts/gen-tech-icons.mjs — do not edit by hand.
//
// Sources:
//   simple-icons v${siVersion} — CC0-1.0.
//   Font Awesome Free (@iconify-json/fa6-brands) — icons licensed CC BY 4.0,
//   https://fontawesome.com/license/free. Used for marks Simple Icons dropped.
//
// Brand marks are the property of their respective owners and are used here
// nominatively, to identify the technologies in the stack.
export type TechIcon = { title: string; viewBox: string; path: string };

export const techIcons: Record<string, TechIcon> = {
${body}
};
`,
);

console.log(`wrote ${entries.length} icons`);
